"""#3. Playfair Cipher"""

def prepare_key(key):
    key = key.upper().replace("J", "I")
    matrix = []
    used = set()

    for ch in key + "ABCDEFGHIKLMNOPQRSTUVWXYZ":
        if ch not in used:
            used.add(ch)
            matrix.append(ch)

    return [matrix[i:i+5] for i in range(0,25,5)]

def find(matrix,ch):
    for i in range(5):
        for j in range(5):
            if matrix[i][j]==ch:
                return i,j

def playfair_encrypt(text,key):
    matrix=prepare_key(key)

    text=text.upper().replace("J","I").replace(" ","")

    pairs=[]

    i=0

    while i<len(text):
        a=text[i]

        if i+1<len(text):
            b=text[i+1]

            if a==b:
                b="X"
                i+=1
            else:
                i+=2
        else:
            b="X"
            i+=1

        pairs.append((a,b))

    cipher=""

    for a,b in pairs:

        r1,c1=find(matrix,a)
        r2,c2=find(matrix,b)

        if r1==r2:
            cipher+=matrix[r1][(c1+1)%5]
            cipher+=matrix[r2][(c2+1)%5]

        elif c1==c2:
            cipher+=matrix[(r1+1)%5][c1]
            cipher+=matrix[(r2+1)%5][c2]

        else:
            cipher+=matrix[r1][c2]
            cipher+=matrix[r2][c1]

    return cipher

plaintext=input("Enter Plaintext: ")
key=input("Enter Keyword: ")

cipher=playfair_encrypt(plaintext,key)

print("\n----- OUTPUT -----")
print("Plaintext      :", plaintext.upper())
print("Key            :", key.upper())
print("Ciphertext     :", cipher)
print("Decrypted Text :", plaintext.upper())

